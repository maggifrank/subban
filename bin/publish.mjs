#!/usr/bin/env node
/* Build the public read-only site into dist/.
 *
 * Snapshots the live count from a running Subban and writes it next to a
 * read-only copy of the app. Deliberately does NOT copy netlify/functions —
 * that is a read/write API with no auth by default, and this deploy is public.
 *
 * Usage: node bin/publish.mjs [--source http://host:8080] [--deploy]
 */

import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist');

const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
};
const SOURCE = (arg('--source', process.env.SUBBAN_SOURCE || 'http://localhost:8080')).replace(/\/$/, '');
const TOKEN = process.env.SUBBAN_TOKEN || '';
const DEPLOY = process.argv.includes('--deploy');

const headers = TOKEN ? { Authorization: `Bearer ${TOKEN}` } : {};

async function get(pathname) {
  const res = await fetch(`${SOURCE}${pathname}`, { headers, signal: AbortSignal.timeout(10000) });
  if (!res.ok) throw new Error(`${pathname} -> HTTP ${res.status}`);
  return res.json();
}

/* Only the files the read-only page actually needs. lib/api.js and lib/rates.js
   are server-side and are left out on purpose. */
const COPY = [
  ['styles.css', 'styles.css'],
  ['public/index.html', 'index.html'],
  ['public/app.js', 'app.js'],
  ['lib/state.js', 'lib/state.js'],
  ['lib/i18n.js', 'lib/i18n.js'],
  ['lib/money.js', 'lib/money.js'],
  ['lib/chart.js', 'lib/chart.js']
];

const NETLIFY_TOML = `# Generated by bin/publish.mjs — a static, read-only build.
# No functions block: this site is public and must have no write path.
[build]
  publish = "."
  command = ""

[[headers]]
  for = "/*"
  [headers.values]
    X-Frame-Options = "DENY"
    X-Content-Type-Options = "nosniff"
    Referrer-Policy = "no-referrer"

[[headers]]
  for = "/*.json"
  [headers.values]
    Cache-Control = "public, max-age=60"
`;

const run = (cmd, args, cwd) => new Promise((resolve, reject) => {
  const child = spawn(cmd, args, { cwd, stdio: 'inherit' });
  child.on('close', (code) => (code === 0 ? resolve() : reject(new Error(`${cmd} exited ${code}`))));
  child.on('error', reject);
});

const state = await get('/api/state');
let rates = null;
try {
  rates = await get('/api/rates');
} catch (err) {
  console.warn(`rates unavailable (${err.message}) — the page will show ISK`);
}

await fs.rm(DIST, { recursive: true, force: true });
await fs.mkdir(path.join(DIST, 'lib'), { recursive: true });
for (const [from, to] of COPY) {
  await fs.copyFile(path.join(ROOT, from), path.join(DIST, to));
}

await fs.writeFile(
  path.join(DIST, 'state.json'),
  JSON.stringify({ ...state, generatedAt: new Date().toISOString() }, null, 2)
);
await fs.writeFile(path.join(DIST, 'rates.json'), JSON.stringify(rates, null, 2));
await fs.writeFile(path.join(DIST, 'netlify.toml'), NETLIFY_TOML);

console.log(`built dist/ from ${SOURCE} — ${state.trips.length} trips`);

if (!DEPLOY) {
  console.log('to publish:  node bin/publish.mjs --deploy');
  process.exit(0);
}

/* Deploy from a copy OUTSIDE the repo. The Netlify CLI resolves its project
   base by walking up from the deploy directory, finds the repo's netlify.toml
   and its netlify/functions folder, and bundles the read/write API into what is
   supposed to be a public read-only site — `--dir` alone does not prevent it.
   Away from the repo there is no functions directory to find. */
const staging = await fs.mkdtemp(path.join(os.tmpdir(), 'subban-public-'));
await fs.cp(DIST, staging, { recursive: true });
await fs.rm(path.join(staging, '.netlify'), { recursive: true, force: true });

const siteId = process.env.SUBBAN_NETLIFY_SITE || await (async () => {
  const raw = await fs.readFile(path.join(ROOT, '.netlify', 'state.json'), 'utf8');
  return JSON.parse(raw).siteId;
})();

await run('netlify', ['deploy', '--prod', '--dir', '.', '--site', siteId], staging);

/* Verify rather than assume: ask Netlify what it actually published. A public
   site with a function on it is a write path, and that is the one thing this
   build must never ship. */
const site = await new Promise((resolve, reject) => {
  const child = spawn('netlify', ['api', 'getSite', '--data', JSON.stringify({ site_id: siteId })],
    { cwd: staging, stdio: ['ignore', 'pipe', 'inherit'] });
  let out = '';
  child.stdout.on('data', (c) => { out += c; });
  child.on('close', (code) => (code === 0 ? resolve(JSON.parse(out)) : reject(new Error(`getSite exited ${code}`))));
});

const fns = site.published_deploy?.available_functions ?? site.published_deploy?.functions ?? [];
if (fns.length) {
  console.error(`\nREFUSING TO PASS: the published deploy contains ${fns.length} function(s): ` +
                `${fns.map((f) => f.n).join(', ')}. The public site must have no write path.`);
  process.exit(1);
}
console.log('verified: published deploy has no functions');
await fs.rm(staging, { recursive: true, force: true });
